import { test } from '@playwright/test'
import { collectErrors, dateInput, login, noHorizontalScroll, ok, resetDb } from './helpers'

test.beforeEach(async ({ request }) => resetDb(request))

test('товариські ігри: окрема кнопка, тип у формі, фільтр на сайті', async ({ page, browser }) => {
  const errors = collectErrors(page)
  await login(page)
  ok((await page.locator('a:has-text("+ Товариська гра")').count()) === 1, 'кнопка «+ Товариська гра» на огляді')
  await page.goto('/admin/matches')
  await page.click('a:has-text("+ Товариська гра")')
  await page.waitForURL(/kind=friendly/)
  ok((await page.textContent('h1')) === 'Нова товариська гра', 'сторінка «Нова товариська гра»')
  ok(await page.isChecked('input[name=kind][value=friendly]'), 'тип «Товариська» вибрано заздалегідь')

  await page.selectOption('#teamId', 'new')
  await page.fill('#opponent', 'Спартак')
  await page.fill('#startsAt', dateInput(5, '19:00'))
  await page.fill('input[name=ourSets]', '2')
  await page.fill('input[name=theirSets]', '2')
  await page.click('main button[type=submit]')
  await page.waitForSelector('.adm-error')
  ok(await page.isChecked('input[name=kind][value=friendly]'), 'після помилки тип гри не збився')
  await page.fill('input[name=ourSets]', '')
  await page.fill('input[name=theirSets]', '')
  await page.click('main button[type=submit]')
  await page.waitForURL(/saved/)

  await page.goto('/admin/matches/new?kind=friendly')
  await page.selectOption('#teamId', 'new')
  await page.fill('#opponent', 'Динамо-Дружба')
  await page.fill('#startsAt', dateInput(-3, '18:00'))
  await page.fill('input[name=ourSets]', '3')
  await page.fill('input[name=theirSets]', '2')
  await page.click('main button[type=submit]')
  await page.waitForURL(/saved/)

  await page.goto('/admin/matches/new')
  ok(await page.isChecked('input[name=kind][value=official]'), 'звичайний матч — офіційний за замовчуванням')
  await page.selectOption('#teamId', 'new')
  await page.fill('#opponent', 'Епіцентр')
  await page.fill('#startsAt', dateInput(12))
  await page.click('main button[type=submit]')
  await page.waitForURL(/saved/)
  ok((await page.locator('.adm-badge-friendly').count()) === 2, 'у списку 2 позначки «Товариська»')

  await page.click('a:has-text("Спартак")')
  await page.waitForURL(/\/admin\/matches\/[0-9a-f-]{36}$/)
  ok(await page.isChecked('input[name=kind][value=friendly]'), 'редагування: тип збережено')
  await page.click('label:has-text("Офіційний матч")')
  await page.click('main button[type=submit]')
  await page.waitForURL(/saved/)
  ok((await page.locator('.adm-badge-friendly').count()) === 1, 'тип змінено на офіційний')
  await page.click('a:has-text("Спартак")')
  await page.waitForURL(/\/admin\/matches\/[0-9a-f-]{36}$/)
  await page.click('label:has-text("Товариська гра")')
  await page.click('main button[type=submit]')
  await page.waitForURL(/saved/)

  // Сайт
  await page.goto('/#matches')
  await page.selectOption('#matches .select-pill select >> nth=0', 'all')
  const titles = async () =>
    (await page.locator('#matches .match-card .team-title:nth-child(3)').allTextContents()).map((s) => s.trim())
  ok((await titles()).length === 3, '«Усі»: 3 гри (майбутні й минулі)')
  await page.click('#matches button:has-text("Товариські")')
  let t = await titles()
  ok(t.length === 2 && t.includes('Спартак') && t.includes('Динамо-Дружба'), `«Товариські»: ${t.join(', ')}`)
  ok((await page.locator('#matches .match-kind').count()) === 2, 'позначка «Товариська» на картках')
  await page.click('#matches button:has-text("Офіційні")')
  t = await titles()
  ok(!t.includes('Спартак') && t.includes('Епіцентр'), `«Офіційні»: ${t.join(', ')}`)
  const empty = await page.locator('#matches .state-message').allTextContents()
  ok(empty.some((s) => s.includes('Результатів за цими умовами ще немає')), `порожній стан: ${empty.join(' | ')}`)

  const m = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage()
  await m.goto('/#matches')
  ok(await noHorizontalScroll(m), 'телефон: без горизонтального скролу')
  ok(errors.length === 0, `без помилок JS: ${errors.join('; ')}`)
})
